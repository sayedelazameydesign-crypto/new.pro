// ===== وضع العرض التجريبي: يعمل بدون أي مفتاح لتجربة الواجهة كاملة =====

import { sleep } from "../../utils";

const DEMO_TEXT = `# أهلاً بك في نواة 🤖

النظام يعمل الآن في **وضع العرض التجريبي** — بدون أي مفاتيح API.

## لتفعيل الذكاء الحقيقي (مجانًا):
1. **مفتاح Gemini مجاني** من [AI Studio](https://aistudio.google.com/apikey) — بدون بطاقة
2. ضعه في متغير البيئة \`GEMINI_API_KEY\`
3. اختر موديلًا حقيقيًا من قائمة الموديلات (أسفل القائمة الجانبية)

> 💡 أنا الآن ردّ محلي حتى تجرب الواجهة كاملة: الكتابة الفورية، الجداول، الكود بتمييز الألوان، الوضع الليلي، وإدارة المحادثات.

بعد إضافة المفتاح ستتحدث مع Gemini فعلًا بنفس هذه التجربة.`;

export async function* demoStream(): AsyncGenerator<string> {
  // بث تدريجي يحاكي الكتابة الحقيقية
  const words = DEMO_TEXT.split(/(\s+)/);
  for (const w of words) {
    yield w;
    await sleep(4);
  }
}
